-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.media_gallery (
  id bigint generated by default as identity primary key,
  title text not null, description text not null default '',
  media_url text not null, media_type text not null check (media_type in ('image','video')) ,
  storage_path text, created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
alter table public.media_gallery enable row level security;
create policy "Admins can view admin list" on public.admin_users for select to authenticated using (user_id = auth.uid());
create policy "Public can view published gallery" on public.media_gallery for select to anon, authenticated using (true);
create policy "Admins can add gallery media" on public.media_gallery for insert to authenticated with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()) and created_by = auth.uid());
create policy "Admins can delete gallery media" on public.media_gallery for delete to authenticated using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types) values ('vpe-media','vpe-media',true,104857600,array['image/jpeg','image/png','image/webp','image/gif','video/mp4','video/webm','video/quicktime']) on conflict (id) do update set public=true, file_size_limit=104857600;
create policy "Public can view VPE media" on storage.objects for select to anon, authenticated using (bucket_id = 'vpe-media');
create policy "Admins can upload VPE media" on storage.objects for insert to authenticated with check (bucket_id = 'vpe-media' and exists (select 1 from public.admin_users a where a.user_id = auth.uid()));
create policy "Admins can delete VPE media" on storage.objects for delete to authenticated using (bucket_id = 'vpe-media' and exists (select 1 from public.admin_users a where a.user_id = auth.uid()));
